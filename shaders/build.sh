#!/usr/bin/env bash
# Compiles every shaders/*.frag (GLSL 450) to SPIR-V with glslc, translates it to MSL with spirv-cross, and writes
# both as C arrays into src/generated/. The generated headers are committed, so a build needs no shader tools; run
# this (make shaders) after changing a shader.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
out="$here/../src/generated"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
mkdir -p "$out"
for source in "$here"/*.frag; do
    name="$(basename "$source" .frag)"
    glslc -fshader-stage=frag -O "$source" -o "$work/$name.spv"
    spirv-cross --msl --msl-version 20100 "$work/$name.spv" --output "$work/$name.msl"
    for kind in spv msl; do
        {
            echo "// Generated by shaders/build.sh from shaders/$name.frag: do not edit."
            echo "#pragma once"
            echo "static const unsigned char ${name}_${kind}[] = {"
            xxd -i < "$work/$name.$kind"
            if [ "$kind" = msl ]; then
                echo ", 0x00"
            fi
            echo "};"
        } > "$out/$name.$kind.h"
    done
    echo "shader $name"
done
